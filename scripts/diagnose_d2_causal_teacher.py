#!/usr/bin/env python3
"""D2-R2 diagnostic for the hand-crafted causal DQI teacher.

The diagnostic compares the causal DQI generated by ``_generate_causal_dqi``
against the canonical future-oracle DQI used in D1-A/D2.  It does not train an
RL agent; it only checks whether the teacher has the right cross-channel rank
signal and whether freshness discounting suppresses the signal too strongly.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd

from cvn_rl.experiments.config import load_config
from cvn_rl.experiments.multi_vehicle_runner import _future_quantile_dqi
from cvn_rl.simulation.multi_traces import generate_multi_vehicle_trace


def _rankdata(values: np.ndarray) -> np.ndarray:
    order = np.argsort(values, kind="mergesort")
    ranks = np.empty(len(values), dtype=float)
    ranks[order] = np.arange(len(values), dtype=float)
    sorted_vals = values[order]
    start = 0
    while start < len(values):
        stop = start + 1
        while stop < len(values) and sorted_vals[stop] == sorted_vals[start]:
            stop += 1
        if stop - start > 1:
            ranks[order[start:stop]] = (start + stop - 1) / 2.0
        start = stop
    return ranks


def _spearman_per_row(a: np.ndarray, b: np.ndarray) -> np.ndarray:
    out = np.full(a.shape[0], np.nan, dtype=float)
    for i in range(a.shape[0]):
        x = a[i]
        y = b[i]
        if np.allclose(x, x[0]) or np.allclose(y, y[0]):
            continue
        rx = _rankdata(x)
        ry = _rankdata(y)
        rx = rx - rx.mean()
        ry = ry - ry.mean()
        denom = np.sqrt(np.sum(rx * rx) * np.sum(ry * ry))
        if denom > 0:
            out[i] = float(np.sum(rx * ry) / denom)
    return out


def _summarize_pair(
    *,
    seed: int,
    update_slots: int,
    history_slots: int,
    trace_slots: int,
    sample_stride: int,
    oracle_update_slots: int,
    future: np.ndarray,
    predicted: np.ndarray,
    fresh: np.ndarray,
    age: np.ndarray,
    validity: np.ndarray,
) -> dict[str, Any]:
    idx = np.arange(0, trace_slots, max(sample_stride, 1), dtype=int)
    f = future[idx]
    p = predicted[idx]
    q = fresh[idx]
    age_s = age[idx]
    validity_s = validity[idx]

    rho_pred = _spearman_per_row(p, f)
    rho_fresh = _spearman_per_row(q, f)
    pred_positive = np.abs(p) > 1e-12
    discount = np.divide(q, p, out=np.full_like(q, np.nan), where=pred_positive)

    def finite_mean(x: np.ndarray) -> float:
        return float(np.nanmean(x)) if np.isfinite(x).any() else float("nan")

    def finite_q(x: np.ndarray, qv: float) -> float:
        return float(np.nanquantile(x, qv)) if np.isfinite(x).any() else float("nan")

    return {
        "seed": seed,
        "dqi_update_slots": update_slots,
        "dqi_history_slots": history_slots,
        "trace_slots": trace_slots,
        "sample_stride": sample_stride,
        "oracle_update_slots": oracle_update_slots,
        "samples": int(len(idx)),
        "spearman_pred_mean": finite_mean(rho_pred),
        "spearman_pred_p10": finite_q(rho_pred, 0.10),
        "spearman_pred_p50": finite_q(rho_pred, 0.50),
        "spearman_fresh_mean": finite_mean(rho_fresh),
        "spearman_fresh_p10": finite_q(rho_fresh, 0.10),
        "spearman_fresh_p50": finite_q(rho_fresh, 0.50),
        "valid_rank_fraction_pred": float(np.isfinite(rho_pred).mean()),
        "valid_rank_fraction_fresh": float(np.isfinite(rho_fresh).mean()),
        "top1_pred_agreement": float((np.argmax(p, axis=1) == np.argmax(f, axis=1)).mean()),
        "top1_fresh_agreement": float((np.argmax(q, axis=1) == np.argmax(f, axis=1)).mean()),
        "future_mean": float(np.mean(f)),
        "predicted_mean": float(np.mean(p)),
        "fresh_mean": float(np.mean(q)),
        "future_std": float(np.std(f)),
        "predicted_std": float(np.std(p)),
        "fresh_std": float(np.std(q)),
        "predicted_p10": float(np.quantile(p, 0.10)),
        "predicted_p50": float(np.quantile(p, 0.50)),
        "predicted_p90": float(np.quantile(p, 0.90)),
        "fresh_p10": float(np.quantile(q, 0.10)),
        "fresh_p50": float(np.quantile(q, 0.50)),
        "fresh_p90": float(np.quantile(q, 0.90)),
        "discount_mean": finite_mean(discount),
        "discount_p10": finite_q(discount, 0.10),
        "discount_p50": finite_q(discount, 0.50),
        "fresh_zero_fraction": float((q <= 1e-12).mean()),
        "predicted_zero_fraction": float((p <= 1e-12).mean()),
        "mae_predicted_future": float(np.mean(np.abs(p - f))),
        "mae_fresh_future": float(np.mean(np.abs(q - f))),
        "age_mean": float(np.mean(age_s)),
        "validity_mean": float(np.mean(validity_s)),
    }


def _aggregate(rows: pd.DataFrame) -> pd.DataFrame:
    metric_cols = [c for c in rows.columns if c not in {"seed"}]
    group_cols = ["dqi_update_slots", "dqi_history_slots"]
    numeric_cols = [c for c in metric_cols if c not in group_cols]
    grouped = rows.groupby(group_cols, as_index=False)[numeric_cols].mean()
    return grouped.sort_values(group_cols).reset_index(drop=True)


def run(args: argparse.Namespace) -> None:
    config = load_config(args.config)
    base_descriptors = dict(config.get("descriptors", {}))
    seeds = [int(s) for s in args.seeds.split(",") if s.strip()]
    updates = [int(x) for x in args.update_slots.split(",") if x.strip()]
    histories = [int(x) for x in args.history_slots.split(",") if x.strip()]
    slots = int(args.slots)
    sample_stride = int(args.sample_stride)

    out = Path(args.output_dir)
    out.mkdir(parents=True, exist_ok=True)
    rows: list[dict[str, Any]] = []

    for update in updates:
        for history in histories:
            for seed in seeds:
                cfg = dict(config)
                descriptors = {
                    **base_descriptors,
                    "skip_causal_dqi": False,
                    "dqi_condition": "predicted",
                    "dqi_update_slots": update,
                    "dqi_history_slots": history,
                    "compute_future_dqi_for_metrics": True,
                    "dqi_causal_teacher": str(args.teacher),
                    "dqi_apply_freshness_discount": not bool(args.disable_freshness_discount),
                }
                cfg["descriptors"] = descriptors
                trace = generate_multi_vehicle_trace(
                    cfg,
                    seed=seed,
                    slots=slots,
                    split="d2_r2_causal_teacher_diagnostic",
                )
                oracle_descriptors = {
                    **descriptors,
                    "dqi_update_slots": int(args.oracle_update_slots),
                }
                future = _future_quantile_dqi(trace, oracle_descriptors)
                rows.append(_summarize_pair(
                    seed=seed,
                    update_slots=update,
                    history_slots=history,
                    trace_slots=slots,
                    sample_stride=sample_stride,
                    oracle_update_slots=int(args.oracle_update_slots),
                    future=future,
                    predicted=trace.dqi_predicted,
                    fresh=trace.fresh_dqi,
                    age=trace.dqi_age,
                    validity=trace.dqi_validity_slots,
                ))
                print(
                    f"done update={update} history={history} seed={seed}",
                    flush=True,
                )

    per_seed = pd.DataFrame(rows)
    summary = _aggregate(per_seed)
    per_seed.to_csv(out / "d2_r2_causal_teacher_per_seed.csv", index=False)
    summary.to_csv(out / "d2_r2_causal_teacher_summary.csv", index=False)

    best_pred = summary.sort_values(
        ["spearman_pred_mean", "top1_pred_agreement"], ascending=False,
    ).head(5)
    best_fresh = summary.sort_values(
        ["spearman_fresh_mean", "top1_fresh_agreement"], ascending=False,
    ).head(5)
    payload = {
        "config": str(Path(args.config)),
        "seeds": seeds,
        "update_slots": updates,
        "history_slots": histories,
        "slots": slots,
        "sample_stride": sample_stride,
        "oracle_update_slots": int(args.oracle_update_slots),
        "teacher": str(args.teacher),
        "disable_freshness_discount": bool(args.disable_freshness_discount),
        "best_predicted_rank": best_pred.to_dict(orient="records"),
        "best_fresh_rank": best_fresh.to_dict(orient="records"),
    }
    (out / "d2_r2_causal_teacher_summary.json").write_text(
        json.dumps(payload, indent=2), encoding="utf-8",
    )
    print(f"wrote {out / 'd2_r2_causal_teacher_summary.csv'}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="configs/e2_d2_causal_dqi_gap.json")
    parser.add_argument("--output-dir", default="results/d2_causal_dqi_gap/diagnostics")
    parser.add_argument("--seeds", default="301,302,303,304,305")
    parser.add_argument("--update-slots", default="1,10,100,1000")
    parser.add_argument("--history-slots", default="100,1000,10000,60000")
    parser.add_argument("--slots", type=int, default=8000)
    parser.add_argument("--sample-stride", type=int, default=10)
    parser.add_argument("--oracle-update-slots", type=int, default=1)
    parser.add_argument("--teacher", default="historical_tail_quantile")
    parser.add_argument("--disable-freshness-discount", action="store_true")
    args = parser.parse_args()
    run(args)


if __name__ == "__main__":
    main()
